/**
 * Builds every third-party asset locally so the deployed page loads nothing
 * from a CDN. Run with `npm run build` (or let the Docker `assets` stage do it).
 *
 *   1. copies the Cairo woff2 subsets actually used (Arabic + Latin, 3 weights)
 *   2. generates @font-face rules with unicode-range so Latin-only pages never
 *      download the Arabic subset
 *   3. compiles Tailwind against index.html + app.js — only the classes those
 *      files really contain end up in the output
 *   4. builds an SVG sprite from the Font Awesome icons the source references,
 *      discovered by scanning, so the sprite can never drift from the markup
 */
import { mkdirSync, copyFileSync, readFileSync, writeFileSync, existsSync, rmSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const frontend = resolve(here, "../frontend");
const assets = resolve(frontend, "assets");
const fontsOut = resolve(assets, "fonts");
const fontsIn = resolve(here, "node_modules/@fontsource/cairo/files");
const iconsIn = resolve(here, "node_modules/@fortawesome/fontawesome-free/svgs");

const WEIGHTS = [400, 600, 700];
const SUBSETS = {
  latin: "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD",
  arabic: "U+0600-06FF,U+0750-077F,U+0870-088E,U+0890-0891,U+0898-08E1,U+08E3-08FF,U+200C-200E,U+2010-2011,U+204F,U+2E41,U+FB50-FDFF,U+FE70-FEFF",
};

/* --------------------------------------------------------------- fonts -- */
rmSync(fontsOut, { recursive: true, force: true });
mkdirSync(fontsOut, { recursive: true });

let faceCss = "/* Cairo — self-hosted (SIL OFL 1.1). Generated by build.mjs. */\n";
for (const [subset, range] of Object.entries(SUBSETS)) {
  for (const weight of WEIGHTS) {
    const file = `cairo-${subset}-${weight}-normal.woff2`;
    const src = resolve(fontsIn, file);
    if (!existsSync(src)) throw new Error(`missing font subset: ${file}`);
    copyFileSync(src, resolve(fontsOut, file));
    faceCss +=
      `@font-face{font-family:'Cairo';font-style:normal;font-weight:${weight};` +
      `font-display:swap;src:url('./fonts/${file}') format('woff2');` +
      `unicode-range:${range};}\n`;
  }
}

/* --------------------------------------------------------------- icons -- */
const sources = ["index.html", "app.js"].map((f) => readFileSync(resolve(frontend, f), "utf8")).join("\n");
const referenced = [...sources.matchAll(/["'#](fa-[a-z0-9-]+)/g)].map((m) => m[1]);
const wanted = [...new Set(referenced)].sort();
const symbols = [];
const missing = [];
for (const name of wanted) {
  const bare = name.replace(/^fa-/, "");
  const file = ["solid", "brands", "regular"]
    .map((style) => resolve(iconsIn, style, `${bare}.svg`))
    .find(existsSync);
  if (!file) { missing.push(name); continue; }
  const svg = readFileSync(file, "utf8");
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  const body = svg.replace(/<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
  symbols.push(`<symbol id="${name}" viewBox="${viewBox}">${body}</symbol>`);
}
if (missing.length) throw new Error(`icons not found in Font Awesome: ${missing.join(", ")}`);

writeFileSync(
  resolve(assets, "icons.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg"><!-- Font Awesome Free 6 (CC BY 4.0) -->\n${symbols.join("\n")}\n</svg>\n`
);

/* ------------------------------------------------------------ tailwind -- */
const input = resolve(here, "tailwind.css");
writeFileSync(
  input,
  `@import "tailwindcss";\n` +
    `@source "${frontend}/index.html";\n` +
    `@source "${frontend}/app.js";\n\n` +
    faceCss +
    readFileSync(resolve(here, "custom.css"), "utf8")
);
execFileSync(
  resolve(here, "node_modules/.bin/tailwindcss"),
  ["-i", input, "-o", resolve(assets, "app.css"), "--minify"],
  { stdio: "inherit" }
);

const bytes = (p) => readFileSync(p).length;
console.log(`icons : ${symbols.length} symbols -> assets/icons.svg (${bytes(resolve(assets, "icons.svg"))} B)`);
console.log(`css   : assets/app.css (${bytes(resolve(assets, "app.css"))} B)`);
console.log(`fonts : ${WEIGHTS.length * 2} woff2 subsets -> assets/fonts/`);
